/**
 * Station facilities data for Lancashire rail stations.
 *
 * Sources: National Rail Enquiries station profiles, Network Rail CORPUS,
 * and on-the-ground survey data. When the NRE Knowledge Base API key is
 * configured, this data can be replaced with live lookups.
 *
 * Covers accessibility, parking, toilets, ticket offices, and amenities.
 */

export type StationFacilities = {
  crs: string;
  name: string;
  staffed: boolean;
  ticketOffice: {
    available: boolean;
    hours: string | null;
    ticketMachine: boolean;
  };
  accessibility: {
    stepFreeAccess: "full" | "partial" | "none";
    stepFreeNote: string | null;
    ramp: boolean;
    lift: boolean;
    accessibleToilet: boolean;
    inductionLoop: boolean;
    tactileSurfaces: boolean;
    wheelchairAvailable: boolean;
    staffAssistance: boolean;
    staffAssistanceNote: string | null;
  };
  parking: {
    available: boolean;
    spaces: number | null;
    blueBadgeSpaces: number | null;
    charges: string | null;
    operator: string | null;
  };
  toilets: {
    available: boolean;
    accessible: boolean;
    babyChange: boolean;
  };
  amenities: {
    wifi: boolean;
    waitingRoom: boolean;
    seatedArea: boolean;
    cafe: boolean;
    shops: boolean;
    bikeStorage: boolean;
    bikeSpaces: number | null;
    taxiRank: boolean;
    carHire: boolean;
    leftLuggage: boolean;
    customerHelpPoint: boolean;
  };
  contact: {
    phone: string | null;
    address: string | null;
  };
};

export type StationFacilitiesSnapshot = {
  crs: string;
  fetchedAt: string;
  facilities: StationFacilities | null;
};

export class StationFacilitiesService {
  getFacilities(crs: string): StationFacilitiesSnapshot {
    const upper = crs.toUpperCase().trim();
    const facilities = LANCASHIRE_STATION_FACILITIES[upper] ?? null;
    return {
      crs: upper,
      fetchedAt: new Date().toISOString(),
      facilities,
    };
  }
}

