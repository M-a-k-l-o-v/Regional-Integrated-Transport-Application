import { execFileSync } from "node:child_process";
import { basename, join } from "node:path";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { generateWorkNote } from "./generate-work-note.mjs";

const WINDOW_MINUTES = Number.parseInt(process.env.NOTES_WINDOW_MINUTES ?? "30", 10);
const INTERVAL_MINUTES = Number.parseFloat(process.env.NOTES_INTERVAL_MINUTES ?? "30");
const INTERVAL_MS = Math.max(1, INTERVAL_MINUTES) * 60 * 1000;
const AUTO_COMMIT = (process.env.NOTES_AUTO_COMMIT ?? "").toLowerCase() === "true";
const RUN_ON_START = (process.env.NOTES_RUN_ON_START ?? "").toLowerCase() === "true";
const STOP_ON_IDLE = (process.env.NOTES_STOP_ON_IDLE ?? "true").toLowerCase() === "true";
const IDLE_STOP_MINUTES = Number.parseFloat(process.env.NOTES_IDLE_STOP_MINUTES ?? "30");

const ROOT = process.cwd();
const EXCLUDED_DIRS = new Set([".git", "node_modules", "dist", "work-notes"]);

function normalizePath(filePath) {
  return filePath.replace(/\\/g, "/");
}

function runGit(args) {
  try {
    return execFileSync("git", args, {
      cwd: process.cwd(),
      stdio: ["ignore", "pipe", "pipe"],
      encoding: "utf8",
    }).trim();
  } catch (err) {
    const stderr = err?.stderr?.toString?.().trim() ?? String(err);
    console.error(`[work-notes] git ${args.join(" ")} failed: ${stderr}`);
    return "";
  }
}

function parseStatusPath(line) {
  const raw = line.slice(3).trim();
  if (!raw) return "";
  const rightSide = raw.includes(" -> ") ? raw.split(" -> ").at(-1) : raw;
  return normalizePath(String(rightSide ?? ""));
}

function meaningfulStatusFingerprint() {
  const raw = runGit(["status", "--porcelain", "--untracked-files=all"]);
  if (!raw) return "";

  const filtered = raw
    .split("\n")
    .filter(Boolean)
    .map(parseStatusPath)
    .map((p) => p.toLowerCase())
    .filter((p) => p && !p.startsWith("work-notes/") && !p.endsWith(".ds_store"))
    .sort();

  return filtered.join("|");
}

function hasFileActivitySince(sinceMs) {
  const stack = [ROOT];

  while (stack.length) {
    const current = stack.pop();
    if (!current) continue;

    let entries = [];
    try {
      entries = readdirSync(current, { withFileTypes: true });
    } catch {
      continue;
    }

    for (const entry of entries) {
      const fullPath = join(current, entry.name);

      if (entry.isDirectory()) {
        if (EXCLUDED_DIRS.has(entry.name)) continue;
        stack.push(fullPath);
        continue;
      }

      if (!entry.isFile()) continue;
      if (entry.name === ".DS_Store") continue;

      try {
        const st = statSync(fullPath);
        if (st.mtimeMs > sinceMs) return true;
      } catch {
        // ignore unreadable files
      }
    }
  }

  return false;
}

function sectionText(markdown, heading) {
  const lines = markdown.split("\n");
  const marker = `## ${heading}`.toLowerCase();
  const start = lines.findIndex((line) => line.trim().toLowerCase() === marker);
  if (start < 0) return "";

  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith("## ")) {
      end = i;
      break;
    }
  }

  return lines
    .slice(start + 1, end)
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

function buildCommitMessage(notePath) {
  let noteContent = "";
  try {
    noteContent = readFileSync(notePath, "utf8");
  } catch {
    // If note read fails, we still create a generic checkpoint message.
  }

  const recent = sectionText(noteContent, "What Changed Recently") || "No summary available";
  const commentary = sectionText(noteContent, "Codex Commentary") || "No commentary available";

  const subject = "chore: auto-checkpoint from work-notes watcher";
  const body = [
    "Generated by notes:watch with NOTES_AUTO_COMMIT=true.",
    `Note: ${basename(notePath)}`,
    `Summary: ${recent}`,
    `Commentary: ${commentary}`,
  ].join("\n");

  return { subject, body };
}

function commitCheckpoint(notePath) {
  const status = runGit(["status", "--porcelain"]);
  if (!status) {
    console.log("[work-notes] auto-commit skipped: no git changes to commit.");
    return;
  }

  runGit(["add", "-A"]);
  const staged = runGit(["diff", "--cached", "--name-only"]);
  if (!staged) {
    console.log("[work-notes] auto-commit skipped: nothing staged after add.");
    return;
  }

  const { subject, body } = buildCommitMessage(notePath);
  const output = runGit(["commit", "-m", subject, "-m", body]);
  if (output) {
    const firstLine = output.split("\n")[0];
    console.log(`[work-notes] auto-commit created: ${firstLine}`);
  }
}

let lastStatusFingerprint = meaningfulStatusFingerprint();
let lastActivityAt = Date.now();

function refreshActivityClock() {
  const now = Date.now();
  const currentFingerprint = meaningfulStatusFingerprint();

  if (currentFingerprint !== lastStatusFingerprint) {
    lastStatusFingerprint = currentFingerprint;
    lastActivityAt = now;
    return "git-status-changed";
  }

  if (hasFileActivitySince(lastActivityAt)) {
    lastActivityAt = now;
    return "filesystem-modified";
  }

  return "";
}

function idleMinutesSinceLastActivity() {
  return (Date.now() - lastActivityAt) / (60 * 1000);
}

function run() {
  try {
    const activitySignal = refreshActivityClock();
    const idleMinutes = idleMinutesSinceLastActivity();

    if (!activitySignal && idleMinutes >= IDLE_STOP_MINUTES) {
      const msg = `[work-notes] idle for ${idleMinutes.toFixed(1)}m (threshold ${IDLE_STOP_MINUTES}m).`;
      if (STOP_ON_IDLE) {
        console.log(`${msg} Stopping watcher.`);
        process.exit(0);
      } else {
        console.log(`${msg} Skipping this cycle.`);
        return;
      }
    }

    const path = generateWorkNote(WINDOW_MINUTES);
    console.log(`[work-notes] wrote ${path}`);

    if (AUTO_COMMIT) {
      commitCheckpoint(path);
    }
  } catch (err) {
    console.error("[work-notes] failed to write note:", err);
  }
}

setInterval(run, INTERVAL_MS);
if (RUN_ON_START) run();

console.log(
  `[work-notes] watcher running. interval=${INTERVAL_MINUTES}m, runOnStart=${RUN_ON_START}, autoCommit=${AUTO_COMMIT}, stopOnIdle=${STOP_ON_IDLE}, idleStopMinutes=${IDLE_STOP_MINUTES}.`
);
